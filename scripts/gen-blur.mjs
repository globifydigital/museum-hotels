// Generates src/lib/blur-data.ts — a tiny blurred data-URL per photo, used as the <Image> blur placeholder.
// Run after adding/replacing images:  node scripts/gen-blur.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const DIR = "public/images";
const files = readdirSync(DIR).filter((f) => /\.(jpe?g)$/i.test(f)); // JPEGs only (skip transparent PNG logo)
const entries = [];
for (const f of files.sort()) {
  const buf = await sharp(join(DIR, f))
    .resize(20, 20, { fit: "inside" })
    .webp({ quality: 40 })
    .toBuffer();
  entries.push(`  "/images/${f}": "data:image/webp;base64,${buf.toString("base64")}",`);
}
const out = `// AUTO-GENERATED by scripts/gen-blur.mjs — do not edit by hand.
// Low-res blur placeholders keyed by image src, so <Image> can show an instant blur while the photo loads.
export const BLUR: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync("src/lib/blur-data.ts", out);
console.log(`wrote ${entries.length} blur placeholders -> src/lib/blur-data.ts`);
